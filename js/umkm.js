// LOAD TABLE
function loadTableUMKM() {

    let filteredData = dataUMKM.filter(item => {

        // gabungkan semua value object jadi 1 text
        const semuaData = Object.values(item)
            .join(" ")
            .toLowerCase();

        return semuaData.includes(searchKeyword);
    });

    filteredData.sort((a, b) => {

        let valueA = a[sortField];
        let valueB = b[sortField];

        // boolean
        if(typeof valueA === "boolean"){

            valueA = valueA ? 1 : 0;
            valueB = valueB ? 1 : 0;
        }

        // string
        if(typeof valueA === "string"){

            const result = valueA.localeCompare(valueB);

            return sortDirection === "asc"
                ? result
                : -result;
        }

        // number
        const result = valueA - valueB;

        return sortDirection === "asc"
            ? result
            : -result;
    });

    const tbody = document.getElementById("umkm-tbl-body");

    tbody.innerHTML = '';

    // PAGINATION
    const start = (currentPage - 1) * rowsPerPage;

    const end = start + rowsPerPage;

    const paginatedData = filteredData.slice(start, end);

    paginatedData.forEach((item) => {

        const isOpened = openedDetailId === item.id;

        tbody.innerHTML += `
        
        <!-- ROW -->
        <tr class="umkm-row"
            onclick="toggleDetail('${item.id}')">

            <td>${item.namaUsaha}</td>
            <td>${item.namaPemilik}</td>
            <td>${item.noTelp}</td>
            <td>${item.alamat}</td>
            <td>${item.kategori}</td>
            <td>${item.status ? 'Aktif' : 'Non-Aktif'}</td>

            <td>
                <div class="actions">
                    <button onclick="event.stopPropagation(); showPopupEditUMKM('${item.id}')">
                        <span class="material-symbols-sharp">edit</span>
                    </button>

                    <button onclick="event.stopPropagation(); showPopupHapus('${item.id}')">
                        <span class="material-symbols-sharp">delete</span>
                    </button>
                </div>

            </td>

        </tr>

        <!-- DETAIL -->
        <tr class="detail-row ${isOpened ? 'show' : ''}">
            <td colspan="6">
                <div class="detail-content">
                    <table class="detail-horizontal-table">
                        <thead>
                            <tr>
                                <th>Email</th>
                                <th>Facebook</th>
                                <th>Instagram</th>
                                <th>WhatsApp</th>
                                <th>Tanggal Registrasi</th>
                                <th>Deskripsi</th>
                            </tr>
                        </thead>
                        <tbody>
                            <tr>
                                <td>${item.email}</td>
                                <td>${item.sosialMedia}</td>
                                <td>${item.sosialMedia}</td>
                                <td>${item.noTelp}</td>
                                <td>${item.tanggalRegistrasi}</td>
                                <td>${item.deskripsi}</td>
                            </tr>
                        </tbody>
                    </table>
                </div>
            </td>
        </tr>
        `;
    });

    loadPagination();
}

function sortTable(field){

    // jika klik field yang sama
    if(sortField === field){

        sortDirection =
            sortDirection === "asc"
                ? "desc"
                : "asc";

    } else {

        sortField = field;
        sortDirection = "asc";
    }

    loadTableUMKM();
}

// PAGINATION
function loadPagination(){

    const pagination =
        document.getElementById("pagination");

    pagination.innerHTML = '';

    const filteredData = dataUMKM.filter(item => {

        const semuaData = Object.values(item)
            .join(" ")
            .toLowerCase();

        return semuaData.includes(searchKeyword);
    });

    const totalPages =
        Math.ceil(filteredData.length / rowsPerPage);

    // PREV
    pagination.innerHTML += `
        <button
            onclick="changePage(${currentPage - 1})"
            ${currentPage === 1 ? 'disabled' : ''}>

            Prev

        </button>
    `;

    // NUMBER
    for(let i = 1; i <= totalPages; i++){

        pagination.innerHTML += `
            <button
                class="
                    ${i === currentPage ? 'active' : ''}
                "
                onclick="changePage(${i})">

                ${i}

            </button>
        `;
    }

    // NEXT
    pagination.innerHTML += `
        <button
            onclick="changePage(${currentPage + 1})"
            ${currentPage === totalPages ? 'disabled' : ''}>

            Next

        </button>
    `;
}

// CHANGE PAGE
function changePage(page){

    const filteredData = dataUMKM.filter(item => {

        const semuaData = Object.values(item)
            .join(" ")
            .toLowerCase();

        return semuaData.includes(searchKeyword);
    });

    const totalPages =
        Math.ceil(filteredData.length / rowsPerPage);

    if(page < 1 || page > totalPages){
        return;
    }

    currentPage = page;

    // tutup detail saat pindah halaman
    openedDetailId = null;

    loadTableUMKM();
}

// TOGGLE DETAIL
function toggleDetail(id){

    // tutup jika klik yang sama
    if(openedDetailId === id){

        openedDetailId = null;

    } else {

        openedDetailId = id;
    }

    loadTableUMKM();

    // scroll agar detail tetap terlihat
    setTimeout(() => {

        const openedRow =
            document.querySelector(".detail-row.show");

        if(openedRow){

            openedRow.scrollIntoView({
                behavior: "smooth",
                block: "nearest"
            });
        }

    }, 50);
}
function closeDetailOutside(e){

    // cek apakah ada detail terbuka
    if(!openedDetailId) return;

    // row UMKM
    const clickedRow =
        e.target.closest(".umkm-row");

    // detail UMKM
    const clickedDetail =
        e.target.closest(".detail-row");

    // jika klik di luar row & detail
    if(!clickedRow && !clickedDetail){

        openedDetailId = null;

        loadTableUMKM();
    }
}

